// Cache isolation tests.
//  1. Cache Enabler (a WordPress page-cache plugin that stores one file per host).
//  2. A reverse-proxy cache keyed on host + URL (how CDNs and most hosts key).
//  3. A reverse-proxy cache keyed on the path only — an unsupported setup,
//     included to prove the risk the documentation warns about is real.
// Run: node --test --test-concurrency=1 tests/e2e/cache.test.mjs
import { test, before, after, describe } from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { PRIMARY, ALIASES, wp, setSettings, request, navigationUrls, isProtected } from './lib.mjs';

const HTML = { Accept: 'text/html' };
const linkHosts = html => [...new Set(navigationUrls(html, 'http://x.invalid/').filter(n => !isProtected(n.url)).map(n => n.url.hostname))];

before(() => {
  wp('plugin', 'activate', 'wp-domain-alias');
  setSettings({});
});
after(() => setSettings({}));

describe('Cache Enabler page cache', () => {
  before(async () => {
    wp('plugin', 'activate', 'cache-enabler');
    // WP-CLI activation does not run Cache Enabler's own activation routine
    // (drop-in + WP_CACHE), so trigger it explicitly.
    wp('eval', 'do_action( "activate_cache-enabler/cache-enabler.php", false );');
    // Cache Enabler writes its settings file on a request after activation
    // and does not cache that request; how many requests that takes varies,
    // so warm up until a cached copy is actually served.
    let ready = false;
    for (let i = 0; i < 6 && !ready; i++) {
      const r = await request(PRIMARY, '/', { headers: HTML });
      ready = r.headers['x-cache-handler'] === 'cache-enabler-engine';
    }
    assert.ok(ready, 'Cache Enabler serves cached pages after warm-up');
    wp('cache-enabler', 'clear');
  });
  after(() => {
    wp('cache-enabler', 'clear');
    wp('eval', 'do_action( "deactivate_cache-enabler/cache-enabler.php", false );');
    wp('plugin', 'deactivate', 'cache-enabler');
  });

  for (const host of [PRIMARY, ...ALIASES]) {
    test(`${host}: cold then warm, hostname kept`, async () => {
      const cold = await request(host, '/about/', { headers: HTML });
      assert.equal(cold.status, 200);
      assert.equal(cold.headers['x-cache-handler'], undefined, 'cold request generated by WordPress');
      const warm = await request(host, '/about/', { headers: HTML });
      assert.equal(warm.headers['x-cache-handler'], 'cache-enabler-engine', 'warm request served from cache');
      assert.deepEqual(linkHosts(warm.body), [host]);
    });
  }
  test('each host still receives its own cached copy after all are warm', async () => {
    for (const host of [PRIMARY, ...ALIASES]) {
      const r = await request(host, '/about/', { headers: HTML });
      assert.equal(r.headers['x-cache-handler'], 'cache-enabler-engine');
      assert.deepEqual(linkHosts(r.body), [host]);
    }
  });
  test('query parameters are preserved (cache bypassed for unknown parameters)', async () => {
    const r = await request('alias-one.test', '/about/?utm_source=qa&gclid=g1', { headers: HTML });
    assert.equal(r.status, 200);
    assert.deepEqual(linkHosts(r.body), ['alias-one.test']);
  });
  test('saving a post purges the alias copies too (integration)', async () => {
    const { about } = JSON.parse(wp('option', 'get', 'wpda_test_ids', '--format=json'));
    for (const host of [PRIMARY, ...ALIASES]) await request(host, '/about/', { headers: HTML }); // warm
    const marker = `Updated ${Date.now()}`;
    wp('post', 'update', String(about), `--post_title=${marker}`);
    for (const host of [PRIMARY, ...ALIASES]) {
      const r = await request(host, '/about/', { headers: HTML });
      assert.ok(r.body.includes(marker), `${host} copy refreshed`);
      assert.deepEqual(linkHosts(r.body), [host]);
    }
    wp('post', 'update', String(about), '--post_title=About');
  });
  test('clearing the complete cache clears alias copies', async () => {
    for (const host of [PRIMARY, ...ALIASES]) await request(host, '/contact/', { headers: HTML });
    wp('cache-enabler', 'clear');
    for (const host of ALIASES) {
      const r = await request(host, '/contact/', { headers: HTML });
      assert.equal(r.headers['x-cache-handler'], undefined, `${host} regenerated after clear`);
    }
  });
  test('content change purges aliases even when the primary copy was never cached', async () => {
    wp('cache-enabler', 'clear');
    await request('alias-one.test', '/test-post-4/', { headers: HTML });
    const cached = await request('alias-one.test', '/test-post-4/', { headers: HTML });
    assert.equal(cached.headers['x-cache-handler'], 'cache-enabler-engine');
    const post = wp('post', 'list', '--name=test-post-4', '--post_type=post', '--field=ID');
    wp('post', 'update', post, '--post_content=Changed body');
    const r = await request('alias-one.test', '/test-post-4/', { headers: HTML });
    assert.equal(r.headers['x-cache-handler'], undefined, 'alias copy purged');
    assert.match(r.body, /Changed body/);
  });
  test('removing an alias purges its cached copies', async () => {
    await request('alias-two.test', '/about/', { headers: HTML });
    const cached = await request('alias-two.test', '/about/', { headers: HTML });
    assert.equal(cached.headers['x-cache-handler'], 'cache-enabler-engine');
    setSettings({ aliases: ALIASES.filter(h => h !== 'alias-two.test') });
    try {
      const r = await request('alias-two.test', '/about/', { headers: HTML });
      assert.equal(r.headers['x-cache-handler'], undefined, 'stale alias copy removed');
      assert.deepEqual(linkHosts(r.body), [PRIMARY], 'removed alias now shows primary links');
    } finally {
      setSettings({});
      wp('cache-enabler', 'clear');
    }
  });
  test('autosaves and revisions do not purge alias copies', async () => {
    await request('alias-one.test', '/contact/', { headers: HTML });
    const { contact } = JSON.parse(wp('option', 'get', 'wpda_test_ids', '--format=json'));
    // _wp_put_post_revision() always stores a revision and fires save_post for it.
    const rev = wp('eval', `echo _wp_put_post_revision( get_post( ${contact} ) );`);
    assert.match(rev, /^\d+$/);
    const r = await request('alias-one.test', '/contact/', { headers: HTML });
    assert.equal(r.headers['x-cache-handler'], 'cache-enabler-engine', 'alias copy kept');
  });
  test('without the integration only primary copies are purged (why it exists)', async () => {
    for (const host of [PRIMARY, 'alias-one.test']) { await request(host, '/test-post-2/', { headers: HTML }); }
    wp('eval', 'remove_all_actions( "cache_enabler_site_cache_cleared" ); remove_all_actions( "shutdown" ); Cache_Enabler::clear_complete_cache();');
    const p = await request(PRIMARY, '/test-post-2/', { headers: HTML });
    const a = await request('alias-one.test', '/test-post-2/', { headers: HTML });
    assert.equal(p.headers['x-cache-handler'], undefined, 'primary copy cleared');
    assert.equal(a.headers['x-cache-handler'], 'cache-enabler-engine', 'alias copy survived');
    wp('cache-enabler', 'clear');
  });
});

/** Tiny caching reverse proxy in front of the test server. */
function proxy(keyOf) {
  const cache = new Map();
  const server = http.createServer(async (req, res) => {
    const key = keyOf(req);
    if (req.method === 'GET' && cache.has(key)) {
      const hit = cache.get(key);
      res.writeHead(hit.status, { ...hit.headers, 'x-proxy-cache': 'HIT' });
      res.end(hit.body);
      return;
    }
    const r = await request(req.headers.host, req.url, { headers: HTML });
    const headers = { 'content-type': r.headers['content-type'] || 'text/html', ...(r.headers.location ? { location: r.headers.location } : {}) };
    if (req.method === 'GET' && r.status === 200) cache.set(key, { status: r.status, headers, body: r.body });
    res.writeHead(r.status, { ...headers, 'x-proxy-cache': 'MISS' });
    res.end(r.body);
  });
  return new Promise(resolve => server.listen(0, '127.0.0.1', () => resolve({ server, port: server.address().port })));
}

describe('reverse-proxy cache keyed on host + URL (supported)', () => {
  let p;
  before(async () => { p = await proxy(req => `${req.headers.host}${req.url}`); });
  after(() => p.server.close());
  test('warm cache keeps every host isolated', async () => {
    for (const round of ['MISS', 'HIT']) {
      for (const host of [PRIMARY, ...ALIASES]) {
        const r = await request(host, '/contact/', { port: p.port });
        assert.equal(r.headers['x-proxy-cache'], round);
        assert.deepEqual(linkHosts(r.body), [host], `${round} ${host}`);
      }
    }
  });
});

describe('reverse-proxy cache keyed on path only (unsupported, demonstrates the risk)', () => {
  let p;
  before(async () => { p = await proxy(req => req.url); });
  after(() => p.server.close());
  test('the alias receives the primary copy — such a cache must be reconfigured', async () => {
    const first = await request(PRIMARY, '/contact/', { port: p.port });
    assert.deepEqual(linkHosts(first.body), [PRIMARY]);
    const poisoned = await request('alias-one.test', '/contact/', { port: p.port });
    assert.equal(poisoned.headers['x-proxy-cache'], 'HIT');
    assert.deepEqual(linkHosts(poisoned.body), [PRIMARY], 'cross-host cache hit observed');
  });
});
